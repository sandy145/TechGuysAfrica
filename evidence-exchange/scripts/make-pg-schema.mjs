/**
 * Produce the Postgres flavour of the schema.
 *
 * Prisma requires the datasource provider to be a literal, so a single schema
 * file cannot serve both local SQLite and a deployed Postgres. Rather than
 * maintain two copies that drift, the deployed schema is generated from the
 * canonical one by swapping the datasource block. Everything else in the model
 * is provider-agnostic.
 */

import fs from "node:fs/promises";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..");
const source = path.join(root, "prisma", "schema.prisma");
const target = path.join(root, "prisma", "schema.postgres.prisma");

const schema = await fs.readFile(source, "utf8");

const swapped = schema.replace(
  /datasource db \{[^}]*\}/,
  `datasource db {
  provider = "postgresql"
  url      = env("DATABASE_URL")
}`,
);

if (!swapped.includes('provider = "postgresql"')) {
  throw new Error("Could not find the datasource block to swap.");
}

await fs.writeFile(
  target,
  `// GENERATED by scripts/make-pg-schema.mjs — do not edit.\n// Edit prisma/schema.prisma; this file is the Postgres deployment flavour.\n\n${swapped}`,
);

console.log(`Wrote ${path.relative(root, target)}`);
